"""Extract the map from the authored Blender district; never change the 3D scene.
blender -b -P Scripts/ExportDistrictMap.py
"""
import bpy,hashlib,json,re
from pathlib import Path
from mathutils import Vector
root=Path(__file__).resolve().parents[1]
source=root/'Assets/Maps/PoliceDistrictRealistic/CityLive_PoliceDistrict_Realistic.blend'
package=json.loads((root/'Assets/Maps/PoliceDistrictGame/manifest.json').read_text())
digest=hashlib.sha256(source.read_bytes()).hexdigest()
if digest!=package['source_blend_sha256']:raise RuntimeError('Map source differs from installed district package')
bpy.ops.wm.open_mainfile(filepath=str(source))
buildings=[];roads=[];trees=[];parks=[];walkways=[];roofs=[];markings=[]
for obj in bpy.context.scene.objects:
 if obj.type!='MESH':continue
 coords=[obj.matrix_world@Vector(v) for v in obj.bound_box]
 lo=[min(p[i] for p in coords) for i in range(3)];hi=[max(p[i] for p in coords) for i in range(3)]
 rect=[round(lo[0],3),round(-hi[1],3),round(hi[0],3),round(-lo[1],3)]
 if obj.name.startswith(('Police_building','Apartment_building','Local_shop')):
  buildings.append(dict(name=obj.name,rect=rect))
 if obj.name.startswith(('Road_EW','Road_NS')):
  cx=(rect[0]+rect[2])/2;cy=(rect[1]+rect[3])/2
  if rect[2]-rect[0]>rect[3]-rect[1]:a=[rect[0],cy];b=[rect[2],cy];width=rect[3]-rect[1]
  else:a=[cx,rect[1]];b=[cx,rect[3]];width=rect[2]-rect[0]
  roads.append(dict(a=a,b=b,width=width))
 if obj.name.startswith('Police_parking'):parks.append(dict(name='Parking',rect=rect,kind=1))
 if obj.name.startswith('Playground_surface'):parks.append(dict(name='Playground',rect=rect,kind=0))
 if obj.name.startswith('Tree_trunk'):trees.append([round(obj.location.x,2),round(-obj.location.y,2)])
 if obj.name.startswith(('Sidewalk_','Walk_segment','Access_path','Entrance_step')):walkways.append(rect)
 if obj.name.startswith('Roof_vent'):roofs.append(rect)
 if obj.name.startswith('Parking_line'):markings.append(rect)
# The hospital is created by CityDistrictWorld.cpp, not present in the Blender file.
buildings.append(dict(name='Hospital',rect=[131,-111,149,-99]))
world=(root/'Source/CityLiveRP/CityDistrictWorld.cpp').read_text()
places=[]
for id,x,y,floors,price in re.findall(r'\{TEXT\("([^"]+)"\),FVector\(([-\d.]+),([-\d.]+),100\),(\d+),(\d+)\}',world):
 label={'North_A':'Северный дом · подъезд 1','North_B':'Северный дом · подъезд 2','South_A':'Южный дом · подъезд 1','South_B':'Южный дом · подъезд 2','Tower_A1':'Башня А · подъезд 1','Tower_A2':'Башня А · подъезд 2','Tower_B1':'Башня Б · подъезд 1','Tower_B2':'Башня Б · подъезд 2'}[id]
 places.append(dict(id=id,label=label,group='Homes',symbol=3,point=[float(x)/100,float(y)/100]))
for variable,id,label,group,symbol in (('PoliceDoor','Police','Полиция','Government',0),('HospitalDoor','Hospital','Больница','Government',1),('CourierDesk','Courier','Работа курьера','Jobs',2)):
 match=re.search(variable+r'\(([-\d.]+),([-\d.]+),100\)',world)
 if not match:raise RuntimeError('Missing runtime location '+variable)
 places.append(dict(id=id,label=label,group=group,symbol=symbol,point=[float(match[1])/100,float(match[2])/100]))
places.extend([dict(id='Parking',label='Парковка полиции',group='Transport',symbol=4,point=[-78,-24]),
 dict(id='Shop',label='Продукты',group='Shops',symbol=5,point=[48,-21]),
 dict(id='Pharmacy',label='Аптека',group='Shops',symbol=5,point=[-107,33]),
 dict(id='Bakery',label='Пекарня',group='Shops',symbol=5,point=[105,36])])
# Asphalt parking lane plus an access link over the open ground to the avenue.
# The access is routed but not drawn as invented asphalt on the basemap.
roads.extend([dict(a=[-125,-24],b=[-31,-24],width=6),dict(a=[-78,-24],b=[-78,0],width=6,access=True)])
captions=[dict(text='СЕВЕРНЫЙ КВАРТАЛ',point=[77,-91]),dict(text='ЮЖНЫЙ КВАРТАЛ',point=[-79,90]),dict(text='ЖИЛЫЕ БАШНИ',point=[80,125])]
data=dict(revision=1,source_blend_sha256=digest,bounds=[-210,-170,210,170],roads=roads,buildings=buildings,trees=trees,parks=parks,places=places,walkways=walkways,roofs=roofs,markings=markings,captions=captions)
if len(buildings)<8 or len(roads)!=8 or len(places)<14:raise RuntimeError('Incomplete district map')
out=root/'Assets/UI';out.mkdir(parents=True,exist_ok=True);(out/'DistrictMap.json').write_text(json.dumps(data,ensure_ascii=False,indent=2),encoding='utf-8')
def pt(v):return '{'+','.join(str(round(x,4)) for x in v)+'}'
lines=['// Generated by Scripts/ExportDistrictMap.py from the authored district. Metres; Unreal Y.','#pragma once','#include "CityMapRoute.h"','namespace CityDistrictMapData {',
 'inline const std::vector<CityMap::Road>& Roads(){static const std::vector<CityMap::Road> Data={']
lines+=['{'+pt(r['a'])+','+pt(r['b'])+','+str(r['width'])+(','+'true' if r.get('access') else '')+'},' for r in roads];lines+=['};return Data;}','inline const std::vector<CityMap::Rect>& Buildings(){static const std::vector<CityMap::Rect> Data={']
lines+=[pt(b['rect'])+',' for b in buildings];lines+=['};return Data;}','inline const std::vector<CityMap::Point>& Trees(){static const std::vector<CityMap::Point> Data={']
lines+=[pt(t)+',' for t in trees];lines+=['};return Data;}','struct Place{const char* Id;const char* Label;const char* Group;int Symbol;CityMap::Point Position;};','inline const std::vector<Place>& Places(){static const std::vector<Place> Data={']
lines+=['{'+','.join((json.dumps(p['id'],ensure_ascii=False),json.dumps(p['label'],ensure_ascii=False),json.dumps(p['group']),str(p['symbol']),pt(p['point'])))+'},' for p in places]
lines+=['};return Data;}']
for name,items in (('Walkways',walkways),('RoofDetails',roofs),('ParkingLines',markings)):
 lines+=['inline const std::vector<CityMap::Rect>& '+name+'(){static const std::vector<CityMap::Rect> Data={']+[pt(r)+',' for r in items]+['};return Data;}']
lines+=['struct Area{CityMap::Rect Bounds;int Kind;};','inline const std::vector<Area>& Areas(){static const std::vector<Area> Data={']
lines+=['{'+pt(p['rect'])+','+str(p['kind'])+'},' for p in parks]+['};return Data;}']
lines+=['struct Caption{const char* Text;CityMap::Point Position;};','inline const std::vector<Caption>& Captions(){static const std::vector<Caption> Data={']
lines+=['{'+json.dumps(c['text'],ensure_ascii=False)+','+pt(c['point'])+'},' for c in captions]+['};return Data;}','}']
(root/'Source/CityLiveRP/CityDistrictMapData.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('DISTRICT_MAP_READY',len(buildings),len(trees),len(places))
