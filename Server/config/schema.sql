CREATE TABLE IF NOT EXISTS citylive_accounts (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 nickname VARCHAR(41) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL UNIQUE,
 password_salt CHAR(32) CHARACTER SET ascii NOT NULL,
 password_hash CHAR(64) CHARACTER SET ascii NOT NULL,
 password_iterations INT UNSIGNED NOT NULL DEFAULT 600000,
 balance INT NOT NULL DEFAULT 20000,
 x DOUBLE NOT NULL DEFAULT 1958.33,
 y DOUBLE NOT NULL DEFAULT 1343.12,
 z DOUBLE NOT NULL DEFAULT 15.36,
 yaw DOUBLE NOT NULL DEFAULT 90,
 has_position TINYINT NOT NULL DEFAULT 0,
 courier TINYINT NOT NULL DEFAULT 0,
 deliveries INT UNSIGNED NOT NULL DEFAULT 0,
 organization TINYINT UNSIGNED NOT NULL DEFAULT 0,
 police_score TINYINT UNSIGNED NOT NULL DEFAULT 0,
 hospital_score TINYINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS citylive_apartments (
 building TINYINT UNSIGNED NOT NULL,
 floor TINYINT UNSIGNED NOT NULL,
 door TINYINT UNSIGNED NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY (building,floor,door),
 KEY citylive_owner (owner_id),
 CONSTRAINT citylive_apartment_owner FOREIGN KEY (owner_id) REFERENCES citylive_accounts(id) ON DELETE CASCADE
) ENGINE=InnoDB;
